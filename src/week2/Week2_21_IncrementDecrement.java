package week2;

/*
2.21 Increment Decrement
Learn how to use increment and decrement operators in
Java to manipulate variables and simplify your code in this
informative class.
 */

public class Week2_21_IncrementDecrement {
    public static void main(String args[]) {

        int num = 1;

        System.out.println(num);
        ++num;

        System.out.println(num);
        ++num;

        System.out.println(num);
        ++num;

        System.out.println(num);
        ++num;

        System.out.println(num);
        ++num;
    }
}
