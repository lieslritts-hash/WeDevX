public class Week2_21_1_Print_NumbersFrom1To5 {
    public static void main(String args[]) {

        int num = 1;

        System.out.println(num);
        ++num;

        System.out.println(num);
        ++num;

        System.out.println(num);
        ++num;

        System.out.println(num);
        ++num;

        System.out.println(num);
        ++num;
    }
}
