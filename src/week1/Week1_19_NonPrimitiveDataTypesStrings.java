package week1;

/*
Understand the Non-Primitive String data type in Java,
including its definition, characteristics, and how it
differs from primitive data types, in this comprehensive
tutorial.
 */

public class Week1_19_NonPrimitiveDataTypesStrings {
    public static void main(String[] args) {
        String firstName = "Steve";
        String lastName = "Jobs";
        String birthDate = "February 24, 1955";
        String deathDate = "October 5, 2011";
        String occupation = "Entrepreneur, inventor, and industrial designer";

        System.out.println("First name: " + firstName);
        System.out.println("Last name: " + lastName);
        System.out.println("Birth date: " + birthDate);
        System.out.println("Death date: " + deathDate);
        System.out.println("Occupation: " + occupation);
    }
}

